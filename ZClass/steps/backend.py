"""分类：应用后端切换 / App Backend Toggle。"""
import os
import shlex
import sys

from ..config import HOME
from ..shell import Shell
from ..style import Style


class BackendSteps:
    @staticmethod
    def _ask(prompt):
        """读取一行终端输入；stdin 不可用（EOF）时回退到 /dev/tty。"""
        try:
            return input(prompt)
        except EOFError:
            pass
        try:
            with open("/dev/tty", encoding="utf-8", errors="replace") as tty:
                sys.stdout.write(prompt)
                sys.stdout.flush()
                line = tty.readline()
        except OSError:
            return None
        return line if line else None

    @staticmethod
    def app_backend():
        print(">>> 应用 Wayland/X11 切换 / Toggle app backend (Wayland <-> X11)...")
        print("    为指定应用生成两个启动器：<app>-wayland 与 <app>-x11")
        print("    Generate two launchers: <app>-wayland and <app>-x11")
        print("    输入 q 可取消 / Enter q to cancel")
        print()

        target = ""
        for _ in range(3):
            raw = BackendSteps._ask("  输入应用命令 / App command (e.g. firefox, code): ")
            if raw is None:
                print(Style.yellow("    ⚠️  无法读取终端输入 / Cannot read terminal input."))
                print("    请在真实终端中直接运行 ./archinit.py")
                print("    Please run ./archinit.py from a real terminal.")
                return Shell.prompt("按 Enter 返回菜单 / Press Enter to return")
            app = raw.strip()
            if not app or app.lower() == "q":
                print("    已取消 / Cancelled.")
                return Shell.prompt("按 Enter 返回菜单 / Press Enter to return")

            if "/" in app:
                cand = os.path.expanduser(app)
                target = cand if os.path.exists(cand) else ""
            else:
                target = Shell.capture(f"command -v {shlex.quote(app)}").strip()
            if target and os.path.exists(target):
                break
            target = ""
            print(Style.yellow(f"    ⚠️  未找到该命令 / Command not found: {app}"))
            print("    请输入已安装应用的命令名（如 firefox、code）/"
                  " Enter an installed command name (e.g. firefox, code).")
            print()
        if not target:
            print(Style.red_bold("    ❌ 已放弃 / Giving up after 3 attempts."))
            return Shell.prompt("按 Enter 返回菜单 / Press Enter to return")

        base = os.path.basename(target)
        dest_dir = os.path.join(HOME, ".local/bin")
        os.makedirs(dest_dir, exist_ok=True)

        header = (
            "#!/bin/sh\n"
            f"# Generated by ArchInit — launch '{base}' with a specific backend\n"
        )
        wl_env = (
            "export QT_QPA_PLATFORM=wayland\n"
            "export GDK_BACKEND=wayland\n"
            "export SDL_VIDEODRIVER=wayland\n"
            "export MOZ_ENABLE_WAYLAND=1\n"
            "export ELECTRON_OZONE_PLATFORM_HINT=wayland\n"
        )
        x11_env = (
            "export QT_QPA_PLATFORM=xcb\n"
            "export GDK_BACKEND=x11\n"
            "export SDL_VIDEODRIVER=x11\n"
            "export MOZ_ENABLE_WAYLAND=0\n"
            "export ELECTRON_OZONE_PLATFORM_HINT=x11\n"
        )
        exec_line = f'exec {shlex.quote(target)} "$@"\n'

        wl_path = os.path.join(dest_dir, f"{base}-wayland")
        x11_path = os.path.join(dest_dir, f"{base}-x11")
        Shell.write_file(wl_path, header + wl_env + exec_line)
        Shell.write_file(x11_path, header + x11_env + exec_line)
        os.chmod(wl_path, 0o755)
        os.chmod(x11_path, 0o755)

        print()
        print(Style.green_bold(f"    ✅ 已生成 / Launchers created in {dest_dir}:"))
        print(f"      {base}-wayland   -> 使用 Wayland 运行 / run on Wayland")
        print(f"      {base}-x11       -> 使用 X11 (XWayland) 运行 / run on X11")
        print()
        print("    提示 / Tip:")
        print("      · 确保 ~/.local/bin 在 PATH 中；运行哪个启动器就切到哪个后端。")
        print("      · Ensure ~/.local/bin is in PATH; run either launcher to switch backend.")
        print(f"      · 也可直接用完整路径： {wl_path}   /   {x11_path}")

        bindir = os.path.join(HOME, ".local/bin")
        path_entries = os.environ.get("PATH", "").split(os.pathsep)
        if bindir not in path_entries:
            print()
            print(Style.yellow(f"    ⚠️  {bindir} 不在 PATH 中 / is not in PATH."))
            print("       请在 ~/.zshrc 或 ~/.bashrc 中加入 / Add to your shell rc:")
            print(f'       export PATH="{bindir}:$PATH"')
        print()
        return Shell.prompt("按 Enter 继续 / Press Enter to continue")
